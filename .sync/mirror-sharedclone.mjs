// One-way mirror: github.com/user1gityup/shared-brain main -> github.com/user1gityup/sharedclone main.
//
// Usage: node mirror-sharedclone.mjs            sync now (force-overwrite the mirror)
//        node mirror-sharedclone.mjs --check    report whether the mirror matches; push nothing
//        node mirror-sharedclone.mjs --detach   start a sync in the background and return (the git hook uses this)
//
// sharedclone is a disposable, non-authoritative copy that ChatGPT can read. The
// direction is fixed by construction: this script reads only the brain's object
// store and the live shared-brain ref, and the only thing it ever writes is the
// sharedclone remote. It never fetches content from sharedclone, never writes a
// brain ref, and holds no credential of its own (git's credential helper on the
// machine that runs it does the push). Whatever sharedclone holds - edits, new
// files, commits, extra branches or tags - is replaced by one deterministic
// commit built from the approved shared-brain main, minus security material.
//
// Trigger: .sync/hooks/reference-transaction runs this with --detach whenever
// refs/remotes/origin/main moves, i.e. after every successful push of the brain
// (by any gatekeeper) and every fetch that brings in a push from another machine.
import { spawn, spawnSync } from 'node:child_process'
import fs from 'node:fs'
import os from 'node:os'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const SOURCE_URL = 'https://github.com/user1gityup/shared-brain.git'
const MIRROR_URL = 'https://github.com/user1gityup/sharedclone.git'
const HERE = path.dirname(fileURLToPath(import.meta.url))
const BRAIN = path.resolve(HERE, '..')
const STATE = path.join(BRAIN, '.sync-state')
const LOG = path.join(STATE, 'mirror-sharedclone.log')
const LOCK = path.join(STATE, 'mirror-sharedclone.lock')
const AGAIN = `${LOCK}.again`
const CHECK = process.argv.includes('--check')
const LOCK_STALE_MS = 20 * 60 * 1000

/** Never mirrored, even when tracked on main. The `keys` branch is never read at all. */
const EXCLUDE = [
  /^\.github\//,
  /^\.sync-state\//,
  /^\.rules-drift\//,
  /(^|\/)[^/]*\.enc$/i,
  /(^|\/)[^/]*\.(key|pem|p12|pfx|jks|keystore|crt|cer|der|csr|kdbx|gpg|asc|ppk)$/i,
  /(^|\/)id_(rsa|dsa|ecdsa|ed25519)(\.pub)?$/i,
  /(^|\/)\.env(\.(?!example$)[^/]*)?$/i,
  /(^|\/)\.?credentials?[^/]*$/i,
  /(^|\/)\.(git-credentials|netrc|npmrc|pypirc)$/i,
  /(^|\/)brain-secrets[^/]*$/i,
]

/** Credential shapes; any hit in the filtered tree aborts the sync. Built from parts so this file never matches itself. */
const SHAPES = [
  ['sk-ant-', '[A-Za-z0-9_-]{20,}'],
  ['sk-or-v1-', '[a-f0-9]{32,}'],
  ['sk-', '(?:proj-)?[A-Za-z0-9]{32,}'],
  ['\\b(?:gh' + 'p|gho|ghu|ghs|ghr)_', '[A-Za-z0-9]{30,}'],
  ['github_' + 'pat_', '[A-Za-z0-9_]{30,}'],
  ['AK' + 'IA', '[0-9A-Z]{16}'],
  ['AI' + 'za', '[0-9A-Za-z_-]{35}'],
  ['nv' + 'api-', '[A-Za-z0-9_-]{30,}'],
  ['xo' + 'x[baprs]-', '[A-Za-z0-9-]{10,}'],
  ['\\bya' + '29\\.', '[A-Za-z0-9._-]{20,}'],
  ['-----BEGIN ' + '[A-Z ]*PRIVATE', ' KEY'],
].map(([head, tail]) => new RegExp(head + tail))

const NOTICE_PATH = 'README.md'

function notice(source, date) {
  return `# sharedclone - NON-AUTHORITATIVE MIRROR

> **sharedclone is a disposable ChatGPT-readable mirror. The authoritative source is user1gityup/shared-brain. Changes made here are ignored and overwritten. Proposed changes must go through the Project Manager and existing gatekeeper workflow.**

- Mirrored from: \`user1gityup/shared-brain\` branch \`main\`, commit \`${source}\` (committed ${date}).
- Direction: one way only, \`shared-brain/main -> sharedclone/main\`. Nothing here is ever read back.
- Every sync replaces this repository's \`main\` with a single generated commit and deletes every other branch and tag. Edits, new files, deletions and commits made here disappear at the next sync.
- This file is generated by \`.sync/mirror-sharedclone.mjs\` in the authoritative brain. A \`README.md\` in the brain itself would appear here as \`README.shared-brain.md\`.

## How ChatGPT proposes a change

ChatGPT analyses and recommends; it does not change authoritative state.

\`ChatGPT -> proposed change request -> Project Manager -> authorized agent/workflow -> gatekeeper -> authoritative Shared Brain\`

Write the proposal in the conversation for the user (what file, what change, why). Do not commit it here: a commit here is discarded, and it reaches nothing.

## Where to start

1. \`MEMORY.md\` - the index; one line per note.
2. \`shared-memory-protocol.md\` - how the store works across agents and machines.
3. \`rules/CLAUDE.md\` - the master rule set every agent follows.
4. \`shared-agent-log.md\` - the cross-agent timeline.
5. \`push-requests.md\` and \`git-gatekeeper-agent.md\` - the gatekeeper queue and who pushes.
6. \`project_agent_project_manager.md\`, \`dsh-presets/projects/agent-project-manager.yaml\` - project-manager state.
7. \`handoff-*.md\` - open and closed work handoffs; \`handoff-council-run-failures.md\` for failures.
8. \`history/README.md\` - redacted Claude Code, Codex, DSH/council and gatekeeper history per machine; \`system/<host>/\` for sanitized settings.

## Deliberately absent

The \`keys\` branch, \`brain-secrets.key\`, \`dsh-credentials.enc\` and any other encrypted or decrypted credential, key, certificate, token, password or environment file. \`.github/\` is dropped so no workflow can run from this copy.
`
}

