function log(msg) {
  const line = `${new Date().toISOString()} ${os.hostname().toLowerCase()} ${msg}`
  console.log(line)
  try { fs.mkdirSync(STATE, { recursive: true }); fs.appendFileSync(LOG, line + '\n') } catch {}
}

const NO_HOOKS = path.join(os.tmpdir(), 'sharedclone-mirror-nohooks')

function git(cwd, args, { input, env, allowFail = false, encoding = 'utf8' } = {}) {
  const r = spawnSync('git', ['-c', `safe.directory=${cwd.replaceAll('\\', '/')}`, '-c', `core.hooksPath=${NO_HOOKS.replaceAll('\\', '/')}`, '-C', cwd, ...args], {
    input, encoding, windowsHide: true, maxBuffer: 512 * 1024 * 1024,
    env: { ...process.env, GIT_TERMINAL_PROMPT: '0', ...env },
  })
  if (r.error) throw r.error
  if (r.status !== 0 && !allowFail) throw new Error(`git ${args[0]} failed (${r.status}): ${String(r.stderr).trim()}`)
  return r
}

function remoteRefs(url) {
  const out = git(BRAIN, ['ls-remote', url]).stdout
  const refs = new Map()
  for (const line of out.split('\n').filter(Boolean)) { const [sha, ref] = line.split('\t'); refs.set(ref, sha) }
  return refs
}

/** Read many blobs in one git process. */
function readBlobs(shas) {
  const out = git(BRAIN, ['cat-file', '--batch'], { input: Buffer.from(shas.join('\n') + '\n'), encoding: 'buffer' }).stdout
  const blobs = new Map()
  let at = 0
  for (const sha of shas) {
    const nl = out.indexOf(10, at)
    const [, , size] = out.subarray(at, nl).toString().split(' ')
    const start = nl + 1
    blobs.set(sha, out.subarray(start, start + Number(size)))
    at = start + Number(size) + 1
  }
  return blobs
}

function build() {
  const live = remoteRefs(SOURCE_URL).get('refs/heads/main')
  if (!live) throw new Error('shared-brain has no main branch on GitHub')
  if (git(BRAIN, ['cat-file', '-e', `${live}^{commit}`], { allowFail: true }).status !== 0) {
    // The fetch moves origin/main, and the hook queues another pass that finds the object.
    log(`source ${live.slice(0, 10)} not in the local brain yet; fetching`)
    git(BRAIN, ['fetch', '--quiet', 'origin', 'main'])
    if (git(BRAIN, ['cat-file', '-e', `${live}^{commit}`], { allowFail: true }).status !== 0) throw new Error(`source ${live} still missing after fetch`)
  }
  const date = git(BRAIN, ['log', '-1', '--format=%ct %cI', live]).stdout.trim().split(' ')

  const entries = git(BRAIN, ['ls-tree', '-r', '-z', '--full-tree', live]).stdout.split('\0').filter(Boolean).map(e => {
    const tab = e.indexOf('\t')
    const [mode, type, sha] = e.slice(0, tab).split(' ')
    return { mode, type, sha, path: e.slice(tab + 1) }
  })
  const excluded = entries.filter(e => e.type !== 'blob' || EXCLUDE.some(re => re.test(e.path)))
  const kept = entries.filter(e => !excluded.includes(e))

  let brainKey = ''
  try { brainKey = fs.readFileSync(path.join(os.homedir(), '.claude', 'brain-secrets.key'), 'utf8').trim() } catch {}
  const blobs = readBlobs([...new Set(kept.map(e => e.sha))])
  const hits = []
  for (const e of kept) {
    const text = blobs.get(e.sha).toString('latin1')
    const shape = SHAPES.find(re => re.test(text))
    if (shape) hits.push(`${e.path}: credential shape`)
    if (brainKey.length >= 16 && text.includes(brainKey)) hits.push(`${e.path}: contains the brain key`)
  }
  if (hits.length) throw new Error(`secret scan refused the sync:\n  ${hits.join('\n  ')}`)

  return { live, date, kept, excluded }
}

function syncOnce() {
  const { live, date, kept, excluded } = build()
  fs.mkdirSync(NO_HOOKS, { recursive: true })
  const tmp = fs.mkdtempSync(path.join(os.tmpdir(), 'sharedclone-mirror-'))
  try {
    git(tmp, ['init', '--quiet', '--bare'])
    const objects = path.resolve(BRAIN, git(BRAIN, ['rev-parse', '--git-common-dir']).stdout.trim(), 'objects')
    fs.writeFileSync(path.join(tmp, 'objects', 'info', 'alternates'), objects + '\n')

    const noticeSha = git(tmp, ['hash-object', '-w', '--stdin'], { input: notice(live, date[1]) }).stdout.trim()
    const lines = kept.map(e => `${e.mode} ${e.sha}\t${e.path === NOTICE_PATH ? 'README.shared-brain.md' : e.path}`)
    lines.push(`100644 ${noticeSha}\t${NOTICE_PATH}`)
    const env = { GIT_INDEX_FILE: path.join(tmp, 'mirror-index') }
    git(tmp, ['update-index', '-z', '--index-info'], { input: lines.join('\0') + '\0', env })
    const tree = git(tmp, ['write-tree'], { env }).stdout.trim()

    // Same source, same commit id: fixed identity, source's own timestamp, no parent.
    const who = { NAME: 'shared-brain mirror (non-authoritative)', EMAIL: 'mirror@shared-brain.invalid', DATE: `@${date[0]} +0000` }
    const commit = git(tmp, ['commit-tree', tree, '-m', `mirror: user1gityup/shared-brain@${live}\n\nNON-AUTHORITATIVE generated copy. Changes here are overwritten by the next sync.`], {
      env: Object.fromEntries(['AUTHOR', 'COMMITTER'].flatMap(r => Object.entries(who).map(([k, v]) => [`GIT_${r}_${k}`, v]))),
    }).stdout.trim()

    const refs = remoteRefs(MIRROR_URL)
    const extras = [...refs.keys()].filter(r => r !== 'HEAD' && r !== 'refs/heads/main' && !r.startsWith('refs/pull/'))
    const current = refs.get('refs/heads/main')
    const state = { source: live, mirrorCommit: commit, mirrorMain: current || null, extras, files: kept.length + 1, excluded: excluded.map(e => e.path) }
    if (current === commit && !extras.length) { log(`in sync: sharedclone main ${commit.slice(0, 10)} = shared-brain ${live.slice(0, 10)}`); return { ...state, pushed: false, inSync: true } }
    if (CHECK) { log(`DIVERGED: sharedclone main ${current?.slice(0, 10) || '(none)'}, expected ${commit.slice(0, 10)}; extra refs: ${extras.join(', ') || 'none'}`); return { ...state, pushed: false, inSync: false } }

    git(tmp, ['push', '--quiet', '--force', MIRROR_URL, `+${commit}:refs/heads/main`, ...extras.map(r => `:${r}`)])
    const after = remoteRefs(MIRROR_URL)
    const left = [...after.keys()].filter(r => r !== 'HEAD' && r !== 'refs/heads/main' && !r.startsWith('refs/pull/'))
    if (after.get('refs/heads/main') !== commit || left.length) throw new Error(`push did not land: main ${after.get('refs/heads/main')}, refs left ${left.join(', ')}`)
    log(`mirrored shared-brain ${live.slice(0, 10)} -> sharedclone ${commit.slice(0, 10)} (${kept.length + 1} files, ${excluded.length} excluded${extras.length ? `, deleted ${extras.join(', ')}` : ''}${current && current !== commit ? `, overwrote ${current.slice(0, 10)}` : ''})`)
    return { ...state, pushed: true, inSync: true }
  } finally {
    fs.rmSync(tmp, { recursive: true, force: true })
  }
}

function takeLock() {
  fs.mkdirSync(STATE, { recursive: true })
  try { fs.writeFileSync(LOCK, String(process.pid), { flag: 'wx' }); return true } catch {}
  try { if (Date.now() - fs.statSync(LOCK).mtimeMs > LOCK_STALE_MS) { fs.rmSync(LOCK, { force: true }); return takeLock() } } catch {}
  fs.writeFileSync(AGAIN, '') // the running sync repeats once more when it finishes
  return false
}

if (process.argv.includes('--detach')) {
  const child = spawn(process.execPath, [fileURLToPath(import.meta.url)], { detached: true, stdio: 'ignore', windowsHide: true, cwd: BRAIN })
  child.unref()
  process.exit(0)
}

if (process.env.SHAREDCLONE_MIRROR_OFF) { log('SHAREDCLONE_MIRROR_OFF set; skipped'); process.exit(0) }
if (CHECK) {
  try { const s = syncOnce(); console.log(JSON.stringify(s, null, 2)); process.exit(s.inSync ? 0 : 1) } catch (err) { log(`check failed: ${err.message}`); process.exit(2) }
}
if (!takeLock()) { log('another sync is running; it will repeat'); process.exit(0) }
let code = 0
try {
  do {
    fs.rmSync(AGAIN, { force: true })
    try { syncOnce(); code = 0 } catch (err) { log(`FAILED: ${err.message}`); code = 2 }
  } while (fs.existsSync(AGAIN))
} finally {
  fs.rmSync(LOCK, { force: true })
}
process.exit(code)
